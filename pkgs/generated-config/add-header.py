"""Annotate known comment-capable formats; retain other sources as symlinks."""

import os
from pathlib import Path
import re
import stat


HASH_SUFFIXES = {
    ".toml",
    ".yaml",
    ".yml",
    ".ini",
    ".conf",
    ".fish",
    ".sh",
    ".bash",
    ".zsh",
    ".nu",
    ".py",
    ".service",
    ".socket",
    ".target",
    ".timer",
    ".desktop",
    ".properties",
}
HASH_NAMES = {
    ".bashrc",
    ".bash_profile",
    ".profile",
    ".zshrc",
    ".zshenv",
    ".zprofile",
    ".zlogin",
    ".gitconfig",
    ".gitignore",
    "gitconfig",
    "htoprc",
    "sketchybarrc",
    "inputrc",
    ".inputrc",
    "ssh_config",
    "sshd_config",
}


def header_style(target):
    path = Path(target)
    suffix = path.suffix.lower()
    if suffix in HASH_SUFFIXES or path.name in HASH_NAMES:
        return "#"
    if suffix == ".lua":
        return "--"
    if suffix in {".jsonc", ".kdl", ".js", ".ts"}:
        return "//"
    if suffix in {".css", ".rasi"}:
        return "/*"
    if suffix == ".xml":
        return "<!--"
    # Extensionless configuration files with known grammars only.
    if target.endswith(("/.ssh/config", "/git/config", "/ghostty/config")):
        return "#"
    return None


def annotate(data, target, repository):
    style = header_style("/" + target.lstrip("/"))
    if style is None or b"\0" in data:
        return data
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return data
    marker = "Generated by the Nix configuration at "
    # A .conf suffix alone does not imply a hash-comment grammar.
    stripped = text.lstrip("\ufeff \t\r\n")
    if Path(target).suffix == ".conf":
        if stripped.startswith("<"):
            style = "<!--"
        elif stripped.startswith("{"):
            return data
    if any(char in repository for char in ("\n", "\r", "\0")):
        raise ValueError("Repository location must be a single line")
    if (style == "/*" and "*/" in repository) or (
        style == "<!--" and "--" in repository
    ):
        raise ValueError("Repository location contains a comment terminator")
    if marker in text[:2048]:
        return data
    lines = [
        f"{marker}{repository}.",
        "DO NOT EDIT this generated file, regardless of who is making the change.",
        f"Edit the sources in {repository}, then run ./rebuild.sh from that directory.",
    ]
    if style == "/*":
        header = "/*\n" + "\n".join(" * " + line for line in lines) + "\n */\n"
    elif style == "<!--":
        header = "<!--\n" + "\n".join(lines) + "\n-->\n"
    else:
        header = "\n".join(style + " " + line for line in lines) + "\n"
    # Keep interpreters, XML declarations and encoding declarations first.
    offset = 1 if text.startswith("\ufeff") else 0
    preamble = text[offset:]
    if preamble.startswith(("#!", "<?xml", "@charset ")):
        end = text.find("\n", offset)
        if end == -1:
            return (text + "\n" + header).encode("utf-8")
        offset = end + 1
    if Path(target).suffix == ".py":
        # PEP 263 permits an encoding cookie on either of the first two lines.
        for match in list(re.finditer(r"[^\n]*\n?", text))[:2]:
            if re.match(r"^[ \t\f]*#.*?coding[:=][ \t]*[-\w.]+", match.group()):
                offset = max(offset, match.end())
    return (text[:offset] + header + text[offset:]).encode("utf-8")


def generate(source, output, target, repository, ancestors=()):
    # Application bundles are software, not configuration trees.
    if (
        target.lstrip("/").startswith("Applications/")
        or ".app" in Path(target).suffixes
    ):
        output.symlink_to(source)
        return
    # Do not freeze mutable/out-of-store symlinks into generated copies.
    if source.is_symlink() and not str(source.resolve()).startswith("/nix/store/"):
        output.symlink_to(source)
        return
    if source.is_dir():
        real = source.resolve()
        if real in ancestors:
            raise ValueError(f"Symlink cycle in managed configuration: {source}")
        output.mkdir()
        for child in sorted(source.iterdir()):
            generate(
                child,
                output / child.name,
                target + "/" + child.name,
                repository,
                ancestors + (real,),
            )
        return
    if not source.is_file() or header_style("/" + target.lstrip("/")) is None:
        output.symlink_to(source)
        return
    data = source.read_bytes()
    result = annotate(data, target, repository)
    if result == data:
        output.symlink_to(source)
    else:
        output.write_bytes(result)
        output.chmod(0o644 | (stat.S_IMODE(source.stat().st_mode) & 0o111))


if __name__ == "__main__":
    generate(
        Path(os.environ["source"]),
        Path(os.environ["out"]),
        os.environ["target"],
        os.environ["repositoryPath"],
    )
